def specs_of(cfg): return cfg
def pil(q):
    cells = ', '.join("{ x: %d, y: %d, part: '%s' }" % (c['x'], c['y'], c['part']) for c in q['cells'])
    order = (", order: [%s]" % ', '.join("'%s'" % o for o in q['order'])) if q.get('order') else ''
    return "{ kind: '%s', shape: '%s', cells: [%s]%s }" % (q['kind'], q['shape'], cells, order)
def room(r, board, specs):
    js = ", ".join("[%s]" % ", ".join("[%d, %d, '%s']" % tuple(c) for c in cells) for cells in r['jewels'])
    ps = (", pillars: [%s]" % ", ".join(pil(q) for q in r['pillars'])) if r.get('pillars') else ''
    sc = (", score: %d" % r['score']) if 'score' in r else ''
    return "{ board: { width: %d, height: %d }, specs: %s, jewels: [%s]%s%s }" % (board[0], board[1], specs, js, ps, sc)
cfg = json.load(open('/tmp/campaign-configs.json'))
levels = json.load(open('/tmp/levels.json')) if os.path.exists('/tmp/levels.json') else {}
for extra in ['/tmp/levels-hard.json', '/tmp/levels-hard2.json', '/tmp/levels-extreme.json', '/tmp/levels-nightmare.json']:
    if os.path.exists(extra):
        for k, v in json.load(open(extra)).items(): levels.setdefault(k, v)
out = ["import type { StoredRoom } from './rooms';", "",
       "/** Generated by prototype/campaign.test.ts (GEN=levels / GEN=pool), then prototype/writeCampaign.py. */", "",
       "/** The 40 campaign levels: 1-10 easy (one new idea each), 11-20 medium, 21-30 hard, 31-40 extreme, 41-50 nightmare. */",
       "export const LEVEL_ROOMS: readonly StoredRoom[] = ["]
for i, c in enumerate(cfg['levels']):
    r = levels.get(str(i))
    if r: out.append("  " + room(r, c['board'], c['specs']) + ",")
out.append("];")
for tier in ['medium', 'hard', 'expert', 'extreme', 'insane', 'nightmare']:
    path = '/tmp/pool-%s.json' % tier
    rooms = json.load(open(path)) if os.path.exists(path) else []
    c = cfg['tiers'][tier]
    out.append("")
    out.append("export const %s_POOL: readonly StoredRoom[] = [" % tier.upper())
    for r in rooms: out.append("  " + room(r, c['board'], c['specs']) + ",")
    out.append("];")
open('src/domain/campaignRooms.ts', 'w').write("\n".join(out) + "\n")
