/** The game passes days as dd/mm or dd/mm/yyyy; written here the local way. */
const koDate = (date: string): string => {
  const [d, m, y] = date.split('/').map((part) => Number(part));
  if (!d || !m) return date;
  return `${y ? `${y}년 ` : ''}${m}월 ${d}일`;
};

