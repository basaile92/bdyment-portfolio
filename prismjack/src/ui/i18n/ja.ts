/** The game passes dates as "DD/MM" or "DD/MM/YYYY"; Japanese readers expect "M月D日" / "YYYY年M月D日". */
const jaDate = (date: string): string => {
  const [d, m, y] = date.split('/').map((part) => Number(part));
  if (!d || !m) return date;
  return `${y ? `${y}年` : ''}${m}月${d}日`;
};

